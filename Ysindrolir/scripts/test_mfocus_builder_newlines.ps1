$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$fixture=Join-Path ([IO.Path]::GetTempPath()) ('yso-mf-'+[guid]::NewGuid().ToString('N').Substring(0,8))
try{
  [IO.Directory]::CreateDirectory((Join-Path $fixture 'scripts')) | Out-Null
  Copy-Item -LiteralPath (Join-Path $root 'Magi') -Destination $fixture -Recurse
  $builder=Join-Path $fixture 'scripts/build_mfocus_alias_body.ps1'
  $original=[IO.File]::ReadAllText((Join-Path $PSScriptRoot 'build_mfocus_alias_body.ps1')).Replace("`r`n","`n")
  $expected=[IO.File]::ReadAllText((Join-Path $root 'Magi/mfocus_alias_body.lua')).Replace("`r`n","`n")
  foreach($newline in @("`n","`r`n")){
    [IO.File]::WriteAllText($builder,$original.Replace("`n",$newline),[Text.UTF8Encoding]::new($false))
    & $builder | Out-Null
    $actual=[IO.File]::ReadAllText((Join-Path $fixture 'Magi/mfocus_alias_body.lua'))
    if($actual -cne $expected){throw 'Mfocus generated bytes depend on PowerShell script checkout line endings'}
  }
  Write-Output 'PASS Mfocus builder produces identical Lua from LF and CRLF checkouts'
}finally{
  $resolved=[IO.Path]::GetFullPath($fixture)
  if((Split-Path $resolved -Parent) -cne [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') -or (Split-Path $resolved -Leaf) -notlike 'yso-mf-*'){throw 'Unsafe Mfocus fixture cleanup'}
  if(Test-Path -LiteralPath $resolved){Remove-Item -LiteralPath $resolved -Recurse -Force}
}
